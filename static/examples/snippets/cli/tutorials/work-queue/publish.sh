#!/bin/bash
# Опубликуйте шесть сообщений в теме "tasks". Параметр --count повторяет
# публикацию указанное число раз, а {{ Count }} заменяется номером сообщения
# (1, 2, 3, ...). Если в группе очереди "workers" два обработчика,
# сервер передаёт каждое сообщение ровно одному из них.
nats pub tasks "task {{ Count }}" --count 6
